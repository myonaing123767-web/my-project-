let audioFiles = {};
let currentAudio = null;
let currentAudioKey = null;
let openParittaKeys = {};

function loadAudioFiles() {
  try {
    const raw = localStorage.getItem(AUDIO_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (parsed && typeof parsed === 'object') {
        Object.keys(parsed).forEach(k => {
          if (parsed[k] && parsed[k].source === 'url' && parsed[k].url) audioFiles[k] = parsed[k];
        });
      }
    }
  } catch(e) { audioFiles = {}; }
}
function saveAudioFiles() {
  try {
    const toSave = {};
    Object.keys(audioFiles).forEach(k => {
      const a = audioFiles[k];
      if (a && a.source === 'url' && a.url) toSave[k] = a;
    });
    localStorage.setItem(AUDIO_KEY, JSON.stringify(toSave));
  } catch(e) {}
}
function openAudioPicker() { document.getElementById('audioPicker').click(); }
function handleAudioFiles(ev) {
  const files = ev.target.files;
  if (!files || files.length === 0) return;
  const availableKeys = PARITTA_DATA.filter(p => !audioFiles[p.key] || audioFiles[p.key].source !== 'url');
  let count = 0;
  for (let i = 0; i < files.length && count < availableKeys.length; i++) {
    const f = files[i];
    if (!f.type.startsWith('audio/')) continue;
    const key = availableKeys[count].key;
    audioFiles[key] = { url: URL.createObjectURL(f), source: 'blob', name: f.name };
    count++;
  }
  renderParitta();
  ev.target.value = '';
  if (count === 0) alert('Audio ဖိုင် မတွေ့ပါ။');
}
