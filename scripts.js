function checkResume() {
  if (!currentUser) return;
  const mine = userRecords.filter(r => r.user === currentUser);
  const inProgress = mine.find(r => r && r.inProgress === true && typeof r.lastLevel === 'number' && r.lastLevel > 0 && r.lastLevel < TOTAL);
  const banner = document.getElementById('resumeBanner');
  const resumeBtn = document.getElementById('resumeBtn');
  if (!banner || !resumeBtn) return;
  if (inProgress) {
    resumeLevel = inProgress.lastLevel;
    const el = document.getElementById('resumeLevel');
    if (el) el.textContent = resumeLevel;
    banner.style.display = 'block';
    resumeBtn.style.display = 'block';
  } else {
    banner.style.display = 'none';
    resumeBtn.style.display = 'none';
  }
}

function startGame() {
  if (!currentUser) { alert('အရင်ဆုံး ဝင်ရောက်ပါ'); return; }
  ensureCtx(); playClick();
  gScore = 0; gIndex = 0; gLocked = false; gStartLevel = 1; gameStarted = true;
  document.getElementById('scoreBox').textContent = '⭐ 0';
  document.getElementById('feedback').textContent = '';
  document.getElementById('feedback').className = 'feedback';
  document.getElementById('gameBtn').style.display = 'none';
  document.getElementById('resumeBtn').style.display = 'none';
  document.getElementById('resumeBanner').style.display = 'none';
  shuffleArr(questions);
  document.getElementById('optionsBox').innerHTML = '';
  showQuestion();
}

function resumeGame() {
  if (!currentUser) return;
  const mine = userRecords.filter(r => r.user === currentUser);
  const inProgress = mine.find(r => r && r.inProgress === true && typeof r.lastLevel === 'number' && r.lastLevel > 0 && r.lastLevel < TOTAL);
  if (!inProgress) { startGame(); return; }
  ensureCtx(); playClick();
  gScore = inProgress.score || 0;
  gIndex = inProgress.lastLevel;
  gLocked = false;
  gStartLevel = inProgress.lastLevel;
  gameStarted = true;
  document.getElementById('scoreBox').textContent = '⭐ ' + gScore;
  document.getElementById('feedback').textContent = '';
  document.getElementById('feedback').className = 'feedback';
  document.getElementById('gameBtn').style.display = 'none';
  document.getElementById('resumeBtn').style.display = 'none';
  document.getElementById('resumeBanner').style.display = 'none';
  document.getElementById('optionsBox').innerHTML = '';
  showQuestion();
}

function showQuestion() {
  if (gIndex >= TOTAL) { endGame(); return; }
  gLocked = false;
  const q = questions[gIndex];
  document.getElementById('levelBadge').textContent = 'Level ' + (gIndex+1) + ' / ' + TOTAL;
  document.getElementById('progressBar').style.width = ((gIndex)/TOTAL*100) + '%';
  document.getElementById('questionBox').innerHTML = '<p>' + q.q + '<br><span style="font-size:.7rem; color:#8b5a2b; font-weight:normal;">[' + (q.cat||'') + ']</span></p>';
  const optBox = document.getElementById('optionsBox');
  optBox.innerHTML = '';
  const letters = ['A','B','C','D'];
  q.opts.forEach((opt, i) => {
    const b = document.createElement('button');
    b.className = 'opt-btn';
    b.innerHTML = '<span class="opt-letter">' + letters[i] + '</span><span>' + opt + '</span>';
    b.onclick = () => answer(i, b);
    optBox.appendChild(b);
  });
}

function answer(sel, btn) {
  if (gLocked) return;
  gLocked = true;
  const q = questions[gIndex];
  const btns = document.querySelectorAll('.opt-btn');
  const fb = document.getElementById('feedback');
  const rect = btn.getBoundingClientRect();
  const cx = rect.left + rect.width/2;
  const cy = rect.top + rect.height/2;

  if (sel === q.ans) {
    btn.classList.add('correct');
    gScore++;
    document.getElementById('scoreBox').textContent = '⭐ ' + gScore;
    fb.textContent = '✅ မှန်ကန်ပါသည်!';
    fb.className = 'feedback ok';
    playCorrect();
    const icon = ICONS_CORRECT[Math.floor(Math.random()*ICONS_CORRECT.length)];
    spawnFlyingIcon(icon, cx - 20, cy - 20);
    spawnConfetti(cx, cy, CONFETTI);
    if (gScore > 0 && gScore % 5 === 0) setTimeout(playLevelUp, 400);
  } else {
    btn.classList.add('wrong');
    btns[q.ans].classList.add('correct');
    fb.textContent = '❌ မှားယွင်းပါသည်။ မှန်ကန်သော အဖြေ: ' + q.opts[q.ans];
    fb.className = 'feedback no';
    playWrong();
    const icon = ICONS_WRONG[Math.floor(Math.random()*ICONS_WRONG.length)];
    spawnFlyingIcon(icon, cx - 20, cy - 20);
  }
  btns.forEach(b => b.disabled = true);
  gIndex++;
  saveInProgress();
  setTimeout(() => {
    if (gIndex < TOTAL) showQuestion();
    else endGame();
  }, 1500);
}

function saveInProgress() {
  if (!currentUser) return;
  if (gIndex >= TOTAL) return;
  const mine = userRecords.filter(r => r.user === currentUser);
  const existing = mine.find(r => r && r.inProgress === true && r.lastLevel < TOTAL);
  if (existing) {
    existing.score = gScore;
    existing.lastLevel = gIndex;
    existing.level = gIndex;
    existing.date = new Date().toLocaleString('en-GB');
  } else {
    userRecords.unshift({
      user: currentUser, score: gScore, level: gIndex,
      total: TOTAL, date: new Date().toLocaleString('en-GB'),
      inProgress: true, lastLevel: gIndex
    });
  }
  saveStorage();
}

function endGame() {
  gameStarted = false;
  document.getElementById('levelBadge').textContent = 'ပြီးဆုံး';
  document.getElementById('progressBar').style.width = '100%';
  const reachedLevel = gIndex;
  document.getElementById('questionBox').innerHTML =
    '<p>🎉 ဂိမ်းပြီးဆုံးပါပြီ!<br>ရမှတ်: ' + gScore + ' / ' + TOTAL + '<br><span style="font-size:.78rem; font-weight:normal; color:#888;">' + getRank(gScore) + '</span></p>';
  document.getElementById('optionsBox').innerHTML = '';
  document.getElementById('feedback').textContent = '';
  document.getElementById('feedback').className = 'feedback';
  const btn = document.getElementById('gameBtn');
  btn.textContent = '🔄 ပြန်ကစားမည်';
  btn.style.display = 'block';
  playGameOver();
  spawnConfetti(window.innerWidth/2, window.innerHeight/2, CONFETTI);
  userRecords = userRecords.filter(r => !(r.user === currentUser && r.inProgress === true));
  saveRecord({
    user: currentUser, score: gScore, level: reachedLevel,
    total: TOTAL, date: new Date().toLocaleString('en-GB'),
    inProgress: false, lastLevel: 0
  });
  checkResume();
  renderHome();
}

function saveRecord(rec) {
  if (!currentUser) return;
  rec.user = currentUser;
  userRecords.unshift(rec);
  if (userRecords.length > 200) userRecords = userRecords.slice(0, 200);
  saveStorage();
}

function getRank(score) {
  const pct = TOTAL > 0 ? score / TOTAL : 0;
  if (pct >= 0.9) return '🌟 အဘိဓမ္မာ ပါရဂူ! ထူးချွန်လှပါသည်။';
  if (pct >= 0.7) return '👍 အလွန်ကောင်းမွန်ပါသည်။';
  if (pct >= 0.5) return '📚 ကောင်းပါသည်။ ထပ်ကြိုးစားပါ။';
  if (pct >= 0.3) return '💪 ကြိုးစားပါ။ နောက်တစ်ခါ ပိုကောင်းလာမည်။';
  return '🪷 မစိုးရိမ်ပါနှင့်။ ထပ်လေ့လာပြီး ပြန်ကစားပါ။';
}

