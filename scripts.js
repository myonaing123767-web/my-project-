let videos = [];
function loadVideos() {
  try {
    const raw = localStorage.getItem(VIDEOS_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed)) videos = parsed.filter(v => v && v.source === 'url');
    }
  } catch(e) { videos = []; }
}
function saveVideos() {
  try {
    const toSave = videos.filter(v => v.source === 'url');
    localStorage.setItem(VIDEOS_KEY, JSON.stringify(toSave));
  } catch(e) {}
}
function openVideoPicker() { document.getElementById('videoPicker').click(); }
function handleVideoFiles(ev) {
  const files = ev.target.files;
  if (!files || files.length === 0) return;
  for (let i = 0; i < files.length; i++) {
    const f = files[i];
    if (!f.type.startsWith('video/')) continue;
    videos.push({
      id: 'v_' + Date.now() + '_' + i,
      title: f.name.replace(/\.[^.]+$/, ''),
      url: URL.createObjectURL(f), type: f.type, source: 'blob', duration: ''
    });
  }
  renderVideos();
  ev.target.value = '';
}
function addDemoVideos() {
  const demos = [
    "ဓမ္မဗျူဟာ - တရားတော် (၁)",
    "ဓမ္မဗျူဟာ - တရားတော် (၂)",
    "ဓမ္မဗျူဟာ - တရားတော် (၃)"
  ];
  demos.forEach((d, i) => {
    videos.push({
      id: 'demo_' + Date.now() + '_' + i,
      title: d, url: '', type: 'video/*', source: 'url', duration: ''
    });
  });
  renderVideos();
  alert('နမူနာ video ၃ ခု ထည့်ပြီးပါပြီ။');
}
function renderVideos() {
  const grid = document.getElementById('videoGrid');
  const count = document.getElementById('videoCount');
  if (count) count.textContent = videos.length + ' ဖိုင်';
  if (!grid) return;
  if (videos.length === 0) {
    grid.innerHTML = `<div class="empty-folder"><div class="icon">📭</div><p>Video မရှိသေးပါ</p></div>`;
    return;
  }
  grid.innerHTML = videos.map((v, i) => `
    <div class="video-item" data-id="${v.id}">
      <button class="video-delete-btn" onclick="deleteVideo(event, '${v.id}')" title="Delete">✕</button>
      <button class="video-rename-btn" onclick="renameVideo(event, '${v.id}')" title="Rename">✏️</button>
      <div class="video-thumb" onclick="openVideo('${v.id}')">
        <div class="placeholder-icon">🎬</div>
        <div class="play-overlay">▶</div>
      </div>
      <div class="video-info">
        <div class="video-title">${escapeHtml(v.title)}</div>
        <div class="video-meta">#${i+1}</div>
      </div>
    </div>
  `).join('');
}
function renameVideo(ev, id) {
  ev.stopPropagation();
  const v = videos.find(x => x.id === id);
  if (!v) return;
  const newName = prompt('Video အမည်အသစ် ထည့်ပါ:', v.title);
  if (newName === null) return;
  const trimmed = newName.trim();
  if (!trimmed) return;
  v.title = trimmed;
  saveVideos();
  renderVideos();
  playClick();
}
function deleteVideo(ev, id) {
  ev.stopPropagation();
  const v = videos.find(x => x.id === id);
  if (!v) return;
  if (!confirm('"' + v.title + '" ကို ဖျက်မှာ သေချာပါသလား?')) return;
  videos = videos.filter(x => x.id !== id);
  saveVideos();
  renderVideos();
  playClick();
}
function openVideo(id) {
  const v = videos.find(x => x.id === id);
  if (!v) return;
  if (!v.url) {
    const newUrl = prompt('Video URL ထည့်ပါ:', v.url || '');
    if (newUrl === null) return;
    if (newUrl.trim()) {
      v.url = newUrl.trim();
      v.source = 'url';
      saveVideos();
      renderVideos();
      showModalVideo(v);
    }
    return;
  }
  showModalVideo(v);
}
function showModalVideo(v) {
  currentVideoId = v.id;
  const modal = document.getElementById('videoModal');
  const video = document.getElementById('modalVideo');
  const title = document.getElementById('modalTitle');
  video.src = v.url;
  title.textContent = v.title;
  modal.classList.add('show');
  video.play().catch(()=>{});
}
function renameCurrentVideo() {
  if (!currentVideoId) return;
  const v = videos.find(x => x.id === currentVideoId);
  if (!v) return;
  const newName = prompt('Video အမည်အသစ် ထည့်ပါ:', v.title);
  if (newName === null) return;
  const trimmed = newName.trim();
  if (!trimmed) return;
  v.title = trimmed;
  saveVideos();
  renderVideos();
  document.getElementById('modalTitle').textContent = trimmed;
  playClick();
}
function closeVideoModal() {
  const modal = document.getElementById('videoModal');
  const video = document.getElementById('modalVideo');
  video.pause();
  video.src = '';
  modal.classList.remove('show');
  currentVideoId = null;
}

