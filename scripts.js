let soundOn = true, audioCtx = null;
function ensureCtx() {
  if (!audioCtx) { try { audioCtx = new (window.AudioContext||window.webkitAudioContext)(); } catch(e) {} }
  if (audioCtx && audioCtx.state === 'suspended') audioCtx.resume();
  return audioCtx;
}
function toggleSound() {
  soundOn = !soundOn;
  document.getElementById('soundBtn').textContent = soundOn ? '🔊' : '🔇';
}
function playTone(f, d, t, v, dl) {
  if (!soundOn) return;
  const ctx = ensureCtx(); if (!ctx) return;
  d=d||0.15; t=t||'sine'; v=v||0.15; dl=dl||0;
  const o=ctx.createOscillator(), g=ctx.createGain();
  o.type=t; o.frequency.value=f; o.connect(g); g.connect(ctx.destination);
  const st=ctx.currentTime+dl;
  g.gain.setValueAtTime(0,st);
  g.gain.linearRampToValueAtTime(v,st+0.02);
  g.gain.exponentialRampToValueAtTime(0.001,st+d);
  o.start(st); o.stop(st+d+0.05);
}
